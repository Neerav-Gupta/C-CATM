"""
Core data structures shared across attackers, monitors, scorers, and the
evaluation harness: a single conversation `Turn` and the full `AttackTrace`
of an attack run (conversation + scores + monitor outcome).
"""

from dataclasses import dataclass, field
from typing import List, Optional
import torch


@dataclass
class Turn:
    """A single turn in a multi-turn attack conversation."""
    role: str                              # "user" or "assistant"
    content: str
    hidden_state: Optional[torch.Tensor] = None  # shape: (d_model,) mean-pooled
    turn_index: int = 0


@dataclass
class AttackTrace:
    """
    Full record of one attack run against a target model: the multi-turn
    conversation plus the scores/labels assigned after the fact by the
    scorers and monitor (see `EvaluationHarness.run_cell`, which populates
    harmbench_label, strongreject_score, flagged_by_monitor, detection_turn,
    and success on an existing trace).
    """
    attack_name: str
    target_behavior: str
    model_id: str
    turns: List[Turn] = field(default_factory=list)
    success: bool = False
    strongreject_score: float = 0.0
    harmbench_label: int = 0               # 0=safe, 1=harmful
    flagged_by_monitor: bool = False
    detection_turn: Optional[int] = None

    def user_turns(self) -> List[Turn]:
        """All turns sent by the attacker/user."""
        return [t for t in self.turns if t.role == "user"]

    def assistant_turns(self) -> List[Turn]:
        """All turns generated by the target model."""
        return [t for t in self.turns if t.role == "assistant"]

    def final_response(self) -> str:
        """The target model's last response, or "" if none yet."""
        asst = self.assistant_turns()
        return asst[-1].content if asst else ""